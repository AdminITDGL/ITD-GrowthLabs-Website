    /* Reveal-on-scroll */
    (function () {
        if (!('IntersectionObserver' in window)) {
            document.querySelectorAll('.reveal').forEach(function (el) { el.classList.add('is-visible'); });
            return;
        }
        var io = new IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    io.unobserve(entry.target);
                }
            });
        }, { threshold: 0.12, rootMargin: '0px 0px -60px 0px' });
        document.querySelectorAll('.reveal').forEach(function (el) { io.observe(el); });
    })();

    /* Animated counters */
    (function () {
        var counters = document.querySelectorAll('.metric__n[data-target]');
        if (!counters.length || !('IntersectionObserver' in window)) {
            counters.forEach(function (c) {
                var target = parseFloat(c.dataset.target);
                var suffix = c.dataset.suffix || '';
                var decimals = parseInt(c.dataset.decimals || '0', 10);
                c.textContent = target.toFixed(decimals) + suffix;
            });
            return;
        }
        function format(n, decimals) {
            return n.toFixed(decimals);
        }
        function animate(el) {
            var target = parseFloat(el.dataset.target);
            var suffix = el.dataset.suffix || '';
            var decimals = parseInt(el.dataset.decimals || '0', 10);
            var dur = 1600;
            var start = null;
            function tick(ts) {
                if (!start) start = ts;
                var t = Math.min(1, (ts - start) / dur);
                // ease-out cubic
                var eased = 1 - Math.pow(1 - t, 3);
                var val = target * eased;
                el.innerHTML = format(val, decimals) + '<span class="unit">' + suffix + '</span>';
                if (t < 1) requestAnimationFrame(tick);
                else el.innerHTML = format(target, decimals) + '<span class="unit">' + suffix + '</span>';
            }
            requestAnimationFrame(tick);
        }
        var io = new IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (entry.isIntersecting) {
                    animate(entry.target);
                    io.unobserve(entry.target);
                }
            });
        }, { threshold: 0.5 });
        counters.forEach(function (c) { io.observe(c); });
    })();
</script>

