<script>
(function () {
    var track   = document.getElementById('track');
    var slides  = Array.prototype.slice.call(track.querySelectorAll('.slide'));
    var prevBtn = document.getElementById('prevBtn');
    var nextBtn = document.getElementById('nextBtn');
    var dotsEl  = document.getElementById('dots');
    var fillEl  = document.getElementById('counterFill');
    var nowEl   = document.getElementById('counterNow');
    var totEl   = document.getElementById('counterTotal');
    var titleEl = document.getElementById('slideTitle');

    var current = 0;
    var total   = slides.length;
    totEl.textContent = String(total).padStart(2, '0');

    slides.forEach(function (s, i) {
        var d = document.createElement('button');
        d.className = 'dot' + (i === 0 ? ' active' : '');
        d.setAttribute('aria-label', 'Slide ' + (i + 1));
        d.addEventListener('click', function () { go(i); });
        dotsEl.appendChild(d);
    });
    var dots = dotsEl.querySelectorAll('.dot');

    function animateCount(el) {
        var target   = parseFloat(el.dataset.target);
        var suffix   = el.dataset.suffix || '';
        var decimals = parseInt(el.dataset.decimals || '0', 10);
        var dur = 1300; var start = null;
        function tick(ts) {
            if (!start) start = ts;
            var t = Math.min(1, (ts - start) / dur);
            var eased = 1 - Math.pow(1 - t, 3);
            var v = target * eased;
            el.innerHTML = v.toFixed(decimals) + '<span class="unit">' + suffix + '</span>';
            if (t < 1) requestAnimationFrame(tick);
            else el.innerHTML = target.toFixed(decimals) + '<span class="unit">' + suffix + '</span>';
        }
        requestAnimationFrame(tick);
    }
    function activateCounters(slideEl) {
        var counters = slideEl.querySelectorAll('.stat__n[data-target]');
        counters.forEach(function (c) { animateCount(c); });
    }

    function go(i) {
        current = Math.max(0, Math.min(total - 1, i));
        track.style.transform = 'translateX(-' + (current * 100) + 'vw)';
        slides.forEach(function (s, idx) { s.classList.toggle('is-active', idx === current); s.scrollTop = 0; });
        dots.forEach(function (d, idx) { d.classList.toggle('active', idx === current); });
        nowEl.textContent = String(current + 1).padStart(2, '0');
        fillEl.style.width = (((current + 1) / total) * 100) + '%';
        titleEl.textContent = slides[current].dataset.title || '';
        prevBtn.disabled = current === 0;
        nextBtn.disabled = current === total - 1;
        activateCounters(slides[current]);
    }

    prevBtn.addEventListener('click', function () { go(current - 1); });
    nextBtn.addEventListener('click', function () { go(current + 1); });

    document.addEventListener('keydown', function (e) {
        if (e.target && (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA')) return;
        if (e.key === 'ArrowRight' || e.key === 'PageDown') { e.preventDefault(); go(current + 1); }
        else if (e.key === 'ArrowLeft' || e.key === 'PageUp') { e.preventDefault(); go(current - 1); }
        else if (e.key === 'Home') { e.preventDefault(); go(0); }
        else if (e.key === 'End') { e.preventDefault(); go(total - 1); }
    });

    /* Touch swipe — only horizontal */
    var touchStartX = null, touchStartY = null;
    track.parentElement.addEventListener('touchstart', function (e) {
        touchStartX = e.changedTouches[0].screenX;
        touchStartY = e.changedTouches[0].screenY;
    }, { passive: true });
    track.parentElement.addEventListener('touchend', function (e) {
        if (touchStartX === null) return;
        var dx = e.changedTouches[0].screenX - touchStartX;
        var dy = e.changedTouches[0].screenY - touchStartY;
        // only treat as slide swipe if horizontal motion dominates (so users can still vertical-scroll dense slides)
        if (Math.abs(dx) > 60 && Math.abs(dx) > Math.abs(dy) * 1.5) {
            if (dx < 0) go(current + 1); else go(current - 1);
        }
        touchStartX = null; touchStartY = null;
    }, { passive: true });

    go(0);
    window.addEventListener('resize', function () { track.style.transform = 'translateX(-' + (current * 100) + 'vw)'; });
})();
